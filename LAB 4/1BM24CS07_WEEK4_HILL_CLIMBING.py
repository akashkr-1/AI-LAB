def calculate_cost(state):
    """
    Calculates the number of attacking pairs of queens.
    Since states are generated by swapping rows, row conflicts are 
    automatically 0. We only need to check diagonal conflicts.
    """
    attacks = 0
    n = len(state)
    for i in range(n):
        for j in range(i + 1, n):
            # Check diagonal attack: absolute row diff == absolute col diff
            if abs(state[i] - state[j]) == abs(i - j):
                attacks += 1
    return attacks

def get_swapped_neighbor(state, i, j):
    """Returns a new state with elements at index i and j swapped."""
    neighbor = list(state)
    neighbor[i], neighbor[j] = neighbor[j], neighbor[i]
    return neighbor

def hill_climbing_swapping(initial_state):
    current_state = list(initial_state)
    current_cost = calculate_cost(current_state)
    n = len(current_state)
    
    step = 0
    print(f"=== Starting Hill-Climbing Search ===")
    print(f"Initial State S0: {current_state} | Cost: {current_cost}\n")
    
    while current_cost > 0:
        step += 1
        print(f"--- Step {step}: Exploring Neighbors of {current_state} ---")
        
        best_neighbor = None
        best_cost = current_cost
        chosen_pair = None
        
        # Generate pairs in lexicographical order: (0,1), (0,2), (0,3), (1,2)...
        # This naturally satisfies the "smallest subscript first" tie-breaking rule.
        for i in range(n):
            for j in range(i + 1, n):
                neighbor = get_swapped_neighbor(current_state, i, j)
                cost = calculate_cost(neighbor)
                print(f"  Swap (x{i}, x{j}) -> State: {neighbor} | Cost: {cost}")
                
                # Strict less-than ensures we keep the FIRST pair seen in 
                # lexicographical order if costs are tied.
                if cost < best_cost:
                    best_cost = cost
                    best_neighbor = neighbor
                    chosen_pair = (i, j)
        
        # If no neighbor improves the current cost, we are stuck in a local optimum
        if best_neighbor is None:
            print(f"\nTerminated: Stuck in a local optimum at state {current_state} with cost {current_cost}.")
            return current_state
            
        # Move to the best neighbor
        current_state = best_neighbor
        current_cost = best_cost
        print(f"\n=> Chosen Move: Swap {chosen_pair} to State {current_state} (New Cost: {current_cost})\n")
        
    print(f"=== Goal Configuration Reached Successfully! ===")
    print(f"Final State: {current_state} | Cost: {current_cost}")
    return current_state

def print_board(state):
    """Prints a visual chess board grid representation."""
    n = len(state)
    for row in range(n):
        line = ""
        for col in range(n):
            if state[col] == row:
                line += " Q "
            else:
                line += " . "
        print(line)

